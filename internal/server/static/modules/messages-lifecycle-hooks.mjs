export const lifecycleHookLocales = Object.freeze(Object.keys(catalogs));

export function lifecycleHookMessages(locale = "zh-CN") {
  return catalogs[locale] || catalogs[locale?.startsWith?.("zh-TW") ? "zh-TW" : locale?.startsWith?.("zh") ? "zh-CN" : "en"] || catalogs.en;
}

export function lifecycleHookMessage(key, values = {}, locale = "zh-CN") {
  const template = lifecycleHookMessages(locale)[key] || catalogs.en[key] || key;
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) => String(values[name] ?? ""));
}
